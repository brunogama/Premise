import PremiseCore
struct RegexPatternParser {
  let characters: [Character]
  let maximumRepeat: Int
  var index = 0

  init(pattern: String, maximumRepeat: Int) {
    self.characters = Array(pattern)
    self.maximumRepeat = max(1, maximumRepeat)
  }

  mutating func parse() throws -> [RegexPiece] {
    var pieces: [RegexPiece] = []
    while index < characters.count {
      if characters[index] == "^" || characters[index] == "$" {
        index += 1
        continue
      }
      var piece = try parseAtom()
      if index < characters.count, let range = parseQuantifier() {
        piece.count = range
      }
      pieces.append(piece)
    }
    return pieces
  }

  private mutating func parseAtom() throws -> RegexPiece {
    let current = characters[index]
    index += 1

    switch current {
    case ".":
      return RegexPiece(characters: printableASCIICharacters, count: 1...1)
    case "[":
      return RegexPiece(characters: try parseCharacterClass(), count: 1...1)
    case "\\":
      return try parseEscape()
    case "(", ")", "|":
      throw StrategyError.invalidRegex(
        label: "regex",
        reason: "groups and alternation are not generated by this strategy"
      )
    default:
      return RegexPiece(characters: [current], count: 1...1)
    }
  }
}

private extension RegexPatternParser {

  private mutating func parseEscape() throws -> RegexPiece {
    guard index < characters.count else {
      throw StrategyError.invalidRegex(
        label: "regex",
        reason: "dangling escape"
      )
    }
    let escaped = characters[index]
    index += 1
    switch escaped {
    case "d": return RegexPiece(characters: Array("0123456789"), count: 1...1)
    case "w":
      let chars =
        "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ"
        + "0123456789_"
      return RegexPiece(characters: Array(chars), count: 1...1)
    case "s": return RegexPiece(characters: [" ", "\t"], count: 1...1)
    default: return RegexPiece(characters: [escaped], count: 1...1)
    }
  }

  private mutating func parseCharacterClass() throws -> [Character] {
    var result: [Character] = []
    var previous: Character?
    let negate = parseNegation()

    while index < characters.count {
      let current = characters[index]
      index += 1
      if current == "]" {
        return classCharacters(result, negated: negate)
      }

      appendClassCharacter(current, previous: &previous, result: &result)
    }

    throw StrategyError.invalidRegex(
      label: "regex",
      reason: "unterminated character class"
    )
  }

  private mutating func parseNegation() -> Bool {
    guard index < characters.count, characters[index] == "^" else {
      return false
    }
    index += 1
    return true
  }

  private mutating func appendClassCharacter(
    _ current: Character,
    previous: inout Character?,
    result: inout [Character]
  ) {
    if current == "-", let previous, index < characters.count,
      characters[index] != "]"
    {
      let end = characters[index]
      index += 1
      result.append(contentsOf: asciiRange(from: previous, through: end))
    } else {
      result.append(current)
      previous = current
    }
  }

  private func classCharacters(
    _ result: [Character],
    negated: Bool
  ) -> [Character] {
    guard negated else {
      return result.isEmpty ? printableASCIICharacters : result
    }
    let excluded = Set(result.map(String.init))
    let remaining = printableASCIICharacters.filter {
      !excluded.contains(String($0))
    }
    return remaining.isEmpty ? printableASCIICharacters : remaining
  }

  private mutating func parseQuantifier() -> ClosedRange<Int>? {
    switch characters[index] {
    case "?":
      index += 1
      return 0...1
    case "*":
      index += 1
      return 0...maximumRepeat
    case "+":
      index += 1
      return 1...maximumRepeat
    case "{":
      return parseBraceQuantifier()
    default:
      return nil
    }
  }

  private mutating func parseBraceQuantifier() -> ClosedRange<Int>? {
    let start = index
    index += 1
    let content = braceContent()
    guard index < characters.count, characters[index] == "}" else {
      index = start
      return nil
    }
    index += 1

    let parts = content.split(separator: ",", omittingEmptySubsequences: false)
    if parts.count == 1, let exact = Int(parts[0]) {
      return exact...exact
    }
    if parts.count == 2, let lower = Int(parts[0]) {
      return braceRange(lower: lower, upper: parts[1])
    }
    index = start
    return nil
  }

  private mutating func braceContent() -> String {
    var content = ""
    while index < characters.count, characters[index] != "}" {
      content.append(characters[index])
      index += 1
    }
    return content
  }

  private func braceRange(lower: Int, upper: Substring) -> ClosedRange<Int> {
    let value =
      upper.isEmpty
      ? min(maximumRepeat, lower + 8) : (Int(upper) ?? lower)
    return lower...max(lower, min(value, maximumRepeat))
  }
}

private let printableASCIICharacters: [Character] = (32...126).compactMap {
  UnicodeScalar($0).map(Character.init)
}

private func asciiRange(
  from start: Character,
  through end: Character
) -> [Character] {
  guard let first = start.unicodeScalars.first?.value,
    let last = end.unicodeScalars.first?.value,
    first <= last,
    first < 128,
    last < 128
  else {
    return [start, end]
  }
  return (first...last).compactMap { UnicodeScalar($0).map(Character.init) }
}
